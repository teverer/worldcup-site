    team_id int NOT NULL,
    player_id int NOT NULL,
    shirt_number int DEFAULT NULL,
    position varchar(20) DEFAULT NULL,
    PRIMARY KEY (team_id, player_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
INSERT INTO tmp_wc2026_full_squad_map (team_id, player_id, shirt_number, position)
SELECT d.team_id, MIN(p.id), d.shirt_number, d.position
FROM tmp_wc2026_full_squad d
JOIN player p ON p.name = d.player_name AND p.nationality = d.nationality
GROUP BY d.team_id, d.player_name, d.shirt_number, d.position;

-- 4. 更新已有名单的球衣号/位置
UPDATE squad s
JOIN tmp_wc2026_full_squad_map m
  ON s.tournament_id = @wc2026 AND s.team_id = m.team_id AND s.player_id = m.player_id
SET s.shirt_number = m.shirt_number, s.position = m.position;

