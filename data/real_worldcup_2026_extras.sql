SELECT @wc2026, m.team_id, m.player_id, m.shirt_number, m.position
FROM tmp_wc2026_full_squad_map m
WHERE NOT EXISTS (
    SELECT 1 FROM squad s WHERE s.tournament_id = @wc2026 AND s.player_id = m.player_id
);

