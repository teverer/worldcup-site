INSERT INTO tournament_team (tournament_id, team_id, group_name)
SELECT tr.id, tm.team_id, d.group_name
FROM tmp_wc2026_tt d
JOIN tournament tr ON tr.year = 2026
JOIN tmp_wc2026_team_map tm ON tm.src = d.team_src
WHERE NOT EXISTS (
    SELECT 1 FROM tournament_team x
    WHERE x.tournament_id = tr.id AND x.team_id = tm.team_id
);

-- 若已有同届参赛行但小组为空/不一致,按真实分组修正(只影响 2026)
UPDATE tournament_team tt
JOIN tournament tr ON tr.id = tt.tournament_id AND tr.year = 2026
JOIN tmp_wc2026_team_map tm ON tm.team_id = tt.team_id
JOIN tmp_wc2026_tt d ON d.team_src = tm.src
SET tt.group_name = d.group_name
WHERE tt.group_name IS NULL OR tt.group_name <> d.group_name;

