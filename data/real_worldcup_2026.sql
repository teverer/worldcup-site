       d.is_penalty, d.is_own_goal, d.is_shootout
FROM tmp_wc2026_goal d
WHERE d.game_id IS NOT NULL AND d.team_id IS NOT NULL AND d.player_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM goal x
    WHERE x.game_id = d.game_id
      AND x.player_id = d.player_id
      AND x.minute <=> d.minute
      AND x.is_penalty = d.is_penalty
      AND x.is_own_goal = d.is_own_goal
      AND x.is_shootout = d.is_shootout
);

