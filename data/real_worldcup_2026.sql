UPDATE tmp_wc2026_goal d
JOIN tournament tr ON tr.year = 2026
JOIN game g ON g.tournament_id = tr.id
           AND g.home_team_id = d.home_team_id
           AND g.away_team_id = d.away_team_id
           AND g.stage = d.stage
SET d.game_id = g.id;

INSERT INTO goal (game_id, team_id, player_id, assist_player_id, minute,
    is_penalty, is_own_goal, is_shootout)
