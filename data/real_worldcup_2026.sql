INSERT INTO team (name, code, continent)
SELECT d.name, d.code, d.continent
FROM tmp_wc2026_team d
WHERE NOT EXISTS (
    SELECT 1 FROM team t WHERE t.code = d.code OR t.name = d.name
);

DROP TEMPORARY TABLE IF EXISTS tmp_wc2026_team_map;
CREATE TEMPORARY TABLE tmp_wc2026_team_map (
    src varchar(60) NOT NULL,
    team_id int NOT NULL,
    PRIMARY KEY (src)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
INSERT INTO tmp_wc2026_team_map (src, team_id)
SELECT d.src, MIN(t.id)
FROM tmp_wc2026_team d
JOIN team t ON (t.code = d.code OR t.name = d.name)
GROUP BY d.src;

