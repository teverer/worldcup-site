INSERT INTO squad (tournament_id, team_id, player_id, shirt_number, position)
SELECT t.id, tm.team_id, p.player_id, d.shirt_number, d.position
FROM tmp_hist_squad d
JOIN tournament t ON t.year = d.year
JOIN tmp_hist_team_id tm ON tm.name = d.team_name
JOIN tmp_hist_player_id p ON p.name = d.player_name AND p.nationality = d.nationality
WHERE NOT EXISTS (
    SELECT 1 FROM squad s
    WHERE s.tournament_id = t.id
      AND (
          s.player_id = p.player_id
          OR (s.team_id = tm.team_id AND s.shirt_number = d.shirt_number)
      )
);

