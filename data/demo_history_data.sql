INSERT INTO team (name, code, continent, intro)
SELECT d.name, d.code, d.continent, d.intro
FROM tmp_hist_team d
WHERE NOT EXISTS (
    SELECT 1 FROM team t WHERE t.code = d.code OR t.name = d.name
);

DROP TEMPORARY TABLE IF EXISTS tmp_hist_team_id;
CREATE TEMPORARY TABLE tmp_hist_team_id (
    name varchar(50) NOT NULL,
    team_id int NOT NULL,
    PRIMARY KEY (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO tmp_hist_team_id (name, team_id)
SELECT d.name, (
    SELECT t.id FROM team t
    WHERE t.name = d.name OR t.code = d.code
    ORDER BY (t.name = d.name) DESC, t.id ASC
    LIMIT 1
)
FROM tmp_hist_team d;

