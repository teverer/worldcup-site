UPDATE tmp_hist_goal d
JOIN tmp_hist_team_id a ON a.name = d.away_name
SET d.away_team_id = a.team_id;

UPDATE tmp_hist_goal d
JOIN tmp_hist_team_id tm ON tm.name = d.team_name
SET d.team_id = tm.team_id;

UPDATE tmp_hist_goal d
JOIN tmp_hist_player_id p ON p.name = d.player_name AND p.nationality = d.nationality
SET d.player_id = p.player_id;

UPDATE tmp_hist_goal d
LEFT JOIN tmp_hist_player_id pa
    ON pa.name = d.assist_name AND pa.nationality = d.assist_nationality
SET d.assist_player_id = pa.player_id;

INSERT INTO goal (game_id, team_id, player_id, assist_player_id, minute,
    is_penalty, is_own_goal, is_shootout)
SELECT g.id, d.team_id, d.player_id, d.assist_player_id, d.minute,
       d.is_penalty, d.is_own_goal, d.is_shootout
FROM tmp_hist_goal d
JOIN tournament t ON t.year = d.year
JOIN game g ON g.tournament_id = t.id
    AND g.stage = d.stage
    AND g.home_team_id = d.home_team_id
    AND g.away_team_id = d.away_team_id
WHERE d.home_team_id IS NOT NULL
  AND d.away_team_id IS NOT NULL
  AND d.team_id IS NOT NULL
  AND d.player_id IS NOT NULL
  AND (d.assist_name IS NULL OR d.assist_player_id IS NOT NULL)
  AND NOT EXISTS (
      SELECT 1 FROM goal gx
      WHERE gx.game_id = g.id
        AND gx.player_id = d.player_id
        AND gx.minute <=> d.minute
        AND gx.is_penalty = d.is_penalty
        AND gx.is_own_goal = d.is_own_goal
        AND gx.is_shootout = d.is_shootout
  );

